#!/bin/sh
# cross-test.sh -- run a module's tests ON the target they were built for.
#
#   cross-test.sh --runner SPEC --tests DIR --out DIR [--kyua NAME] [--html]
#                 [--ship VAR=dir1:dir2 ...]
#
# bmake test calls this when TEST_RUNNER.<os>-<arch> (or TEST_RUNNER) names a
# runner (cross-test-runner-dec). The unit of work is the whole tests
# directory: kyua hands every ATF program a results file on its own filesystem,
# so the programs cannot be wrapped one by one. The script
#   1. stages DIR (the Kyuafile and the test programs) and every --ship
#      directory (libraries, programs under test, data) in a temporary tree;
#   2. writes run.sh there, which runs on the target, puts the shipped
#      directories first in VAR, runs `kyua test`, and writes the JUnit report
#      (and the HTML report with --html) into out/;
#   3. has the runner carry the tree to the target, run run.sh, and bring
#      out/ back; the contents are copied to --out;
#   4. exits with the tests' status (kyua's: non-zero when a test failed).
# A test never relies on the build host's absolute paths: the shipped copies are
# named by the environment on the target (cross-test-ships-dependencies-req).
#
# SPEC is one of
#   ssh:[user@]host[:port]   ssh and tar; ssh options come from BMK_SSH_OPTS
#   docker:<image>[@<platform>]   a throw-away container (docker create/cp/exec)
#   cmd:<program>            <program> <staged-dir>: it must run
#                            `sh <staged-dir>/run.sh <staged-dir>` wherever the
#                            target is and leave <staged-dir>/out behind
#   local                    run it here (useful for trying a runner out)
# @impl 0f87-6adc-9b69-7c32
set -eu

die() { echo "cross-test: $*" >&2; exit 2; }

RUNNER=""; TESTS=""; OUT=""; KYUA=kyua; HTML=no; SHIPS=""
while [ $# -gt 0 ]; do
    case "$1" in
        --runner) RUNNER=$2; shift 2 ;;
        --tests)  TESTS=$2;  shift 2 ;;
        --out)    OUT=$2;    shift 2 ;;
        --kyua)   KYUA=$2;   shift 2 ;;
        --html)   HTML=yes;  shift ;;
        --ship)   SHIPS="$SHIPS
$2"; shift 2 ;;
        *) die "unknown argument '$1'" ;;
    esac
done
[ -n "$RUNNER" ] && [ -n "$TESTS" ] && [ -n "$OUT" ] || die "usage: --runner SPEC --tests DIR --out DIR"
[ -d "$TESTS" ] || die "tests directory '$TESTS' does not exist"
mkdir -p "$OUT"

STAGE=$(mktemp -d "${TMPDIR:-/tmp}/bmk-xtest.XXXXXX")
trap 'rm -rf "$STAGE"' EXIT INT TERM
mkdir -p "$STAGE/tests" "$STAGE/ship" "$STAGE/out"

# tar that leaves no macOS metadata sidecars (AppleDouble files turn into
# literal ._foo files on the target) when the tar in use knows how.
if COPYFILE_DISABLE=1 tar --no-xattrs --no-acls --no-mac-metadata -cf /dev/null /dev/null 2>/dev/null; then
    TAROPT="--no-xattrs --no-acls --no-mac-metadata"
else
    TAROPT=""
fi
tarc() { COPYFILE_DISABLE=1 tar $TAROPT -cf - "$@"; }
copydir() { # copydir <from> <to>
    mkdir -p "$2"; tarc -C "$1" . | tar -xf - -C "$2"
}

copydir "$TESTS" "$STAGE/tests"

# --- run.sh: the target-side half ------------------------------------------
{
    echo '#!/bin/sh'
    echo '# generated by cross-test.sh; runs ON the target. $1 = the staged directory'
    echo 'd=$1'
    # a non-login ssh/docker shell lacks the prefixes kyua and atf install into
    echo 'PATH="$d/tests:$PATH:/usr/pkg/bin:/usr/pkg/sbin:/usr/local/bin:/usr/local/sbin:/usr/sbin"; export PATH'
} > "$STAGE/run.sh"

# ship_one VAR dir1:dir2 -- copy each existing directory into the stage and add
# the line to run.sh that puts the copies first in VAR on the target.
ship_one() {
    _var=$1; _i=0; _staged=""
    _old=$IFS; IFS=:; set -- $2; IFS=$_old
    for _d in "$@"; do
        [ -n "$_d" ] && [ -d "$_d" ] || continue
        copydir "$_d" "$STAGE/ship/$_var.$_i"
        _staged="${_staged:+$_staged:}\$d/ship/$_var.$_i"
        _i=$((_i + 1))
    done
    [ -z "$_staged" ] || echo "$_var=\"$_staged\${$_var:+:\$$_var}\"; export $_var" >> "$STAGE/run.sh"
}
printf '%s\n' "$SHIPS" | while IFS= read -r spec; do
    [ -n "$spec" ] || continue
    ship_one "${spec%%=*}" "${spec#*=}"
done

cat >> "$STAGE/run.sh" <<EOF
mkdir -p "\$d/out"
cd "\$d/tests" || exit 1
if ! command -v $KYUA >/dev/null 2>&1; then
    echo "cross-test: $KYUA is not installed on the target (it needs kyua and atf)" >&2
    exit 127
fi
rc=0
$KYUA test -k Kyuafile -r "\$d/results.db" || rc=\$?
$KYUA report-junit -r "\$d/results.db" --output "\$d/out/test-results.xml" || true
EOF
if [ "$HTML" = yes ]; then
    echo "$KYUA report-html -r \"\$d/results.db\" --force --output \"\$d/out/test-report-html\" || true" >> "$STAGE/run.sh"
fi
echo 'exit $rc' >> "$STAGE/run.sh"

# --- transports --------------------------------------------------------------
rc=0
kind=${RUNNER%%:*}; rest=${RUNNER#*:}
case "$kind" in
    local)
        sh "$STAGE/run.sh" "$STAGE" || rc=$?
        ;;
    cmd)
        [ -n "$rest" ] && [ "$rest" != "$RUNNER" ] || die "cmd: needs a program (TEST_RUNNER=cmd:/path/to/program)"
        "$rest" "$STAGE" || rc=$?
        ;;
    ssh)
        [ -n "$rest" ] && [ "$rest" != "$RUNNER" ] || die "ssh: needs a host (TEST_RUNNER=ssh:[user@]host[:port])"
        host=$rest; port=""
        case "$host" in
            *:[0-9]*) port=${host##*:}; host=${host%:*} ;;
        esac
        # BMK_SSH_OPTS is a list of options by design (key, known_hosts policy)
        # shellcheck disable=SC2086
        SSH="ssh -o BatchMode=yes ${BMK_SSH_OPTS:-} ${port:+-p $port} $host"
        remote=$($SSH -n 'mktemp -d /tmp/bmk-xtest.XXXXXX' 2>/dev/null) \
            || die "cannot reach $RUNNER (ssh failed; set BMK_SSH_OPTS for keys and options)"
        tarc -C "$STAGE" . | $SSH "tar -xf - -C $remote"
        $SSH -n "sh $remote/run.sh $remote" || rc=$?
        $SSH -n "tar -cf - -C $remote/out ." 2>/dev/null | tar -xf - -C "$STAGE/out" || true
        $SSH -n "rm -rf $remote" 2>/dev/null || true
        ;;
    docker)
        [ -n "$rest" ] && [ "$rest" != "$RUNNER" ] || die "docker: needs an image (TEST_RUNNER=docker:<image>[@<platform>])"
        image=${rest%@*}; plat=""
        case "$rest" in *@*) plat=${rest##*@} ;; esac
        cid=$(docker create ${plat:+--platform "$plat"} "$image" sleep 86400) \
            || die "cannot create a container from '$image'"
        trap 'docker rm -f "$cid" >/dev/null 2>&1 || true; rm -rf "$STAGE"' EXIT INT TERM
        docker start "$cid" >/dev/null
        docker exec "$cid" mkdir -p /xtest
        docker cp "$STAGE/." "$cid:/xtest/"
        docker exec "$cid" sh /xtest/run.sh /xtest || rc=$?
        docker cp "$cid:/xtest/out/." "$STAGE/out/" 2>/dev/null || true
        ;;
    *)
        die "unknown runner '$RUNNER' (want ssh:, docker:, cmd: or local)"
        ;;
esac

# Bring the reports back. Missing results are an infrastructure failure, not a
# test failure -- say so, and keep the tests' own status when there is one.
if [ -n "$(ls -A "$STAGE/out" 2>/dev/null)" ]; then
    copydir "$STAGE/out" "$OUT"
else
    echo "cross-test: no results came back from $RUNNER" >&2
    [ "$rc" -ne 0 ] || rc=1
fi
exit "$rc"
